CREATE OR REPLACE FUNCTION public.bootstrap_first_owner(
  target_email text,
  target_organization_id uuid
)
RETURNS uuid
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  normalized_email text := lower(btrim(target_email));
  target_user_id uuid;
  invitation_id uuid;
BEGIN
  IF normalized_email IS NULL OR normalized_email = '' OR position('@' IN normalized_email) <= 1 THEN
    RAISE EXCEPTION 'A valid owner email is required.';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM public.organizations WHERE id = target_organization_id
  ) THEN
    RAISE EXCEPTION 'Organization does not exist.';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.organization_members
    WHERE organization_id = target_organization_id
      AND role IN ('SUPER_ADMIN', 'ORG_ADMIN')
      AND COALESCE(email, '') <> normalized_email
  ) THEN
    RAISE EXCEPTION 'This organization already has a different owner. Use Team Access in the app.';
  END IF;

  SELECT id INTO target_user_id
  FROM auth.users
  WHERE lower(email) = normalized_email
  ORDER BY created_at ASC
  LIMIT 1;

  IF target_user_id IS NOT NULL THEN
    INSERT INTO public.organization_members (organization_id, user_id, role, email)
    VALUES (target_organization_id, target_user_id, 'ORG_ADMIN', normalized_email)
    ON CONFLICT (organization_id, user_id) DO UPDATE SET
      role = 'ORG_ADMIN',
      email = EXCLUDED.email,
      updated_at = now();
    RETURN target_user_id;
  END IF;

  INSERT INTO public.organization_invitations (
    organization_id,
    email,
    role,
    status,
    expires_at
  )
  VALUES (
    target_organization_id,
    normalized_email,
    'ORG_ADMIN',
    'PENDING',
    now() + interval '30 days'
  )
  ON CONFLICT (organization_id, lower(email)) WHERE status = 'PENDING'
  DO UPDATE SET
    role = 'ORG_ADMIN',
    expires_at = now() + interval '30 days',
    last_error = NULL,
    updated_at = now()
  RETURNING id INTO invitation_id;

  RETURN invitation_id;
END;
$$;

REVOKE EXECUTE ON FUNCTION public.bootstrap_first_owner(text, uuid) FROM PUBLIC, anon, authenticated;

