CREATE OR REPLACE FUNCTION private.is_org_admin(target_organization_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.organization_members
    WHERE organization_id = target_organization_id
      AND user_id = (SELECT auth.uid())
      AND role IN ('SUPER_ADMIN', 'ORG_ADMIN')
  );
$$;

CREATE OR REPLACE FUNCTION private.can_manage_school(target_school_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.schools
    JOIN public.organization_members
      ON organization_members.organization_id = schools.organization_id
    WHERE schools.id = target_school_id
      AND organization_members.user_id = (SELECT auth.uid())
      AND organization_members.role IN ('SUPER_ADMIN', 'ORG_ADMIN', 'SCHOOL_ADMIN')
  );
$$;

REVOKE ALL ON FUNCTION private.is_org_admin(uuid) FROM PUBLIC;
REVOKE ALL ON FUNCTION private.can_manage_school(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION private.is_org_admin(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION private.can_manage_school(uuid) TO authenticated;

CREATE OR REPLACE FUNCTION public.hook_require_invitation(event jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  requested_email text := lower(btrim(event->'user'->>'email'));
BEGIN
  IF requested_email IS NULL OR requested_email = '' THEN
    RETURN jsonb_build_object(
      'error', jsonb_build_object(
        'http_code', 403,
        'message', 'FlowPilot registration requires an invited email address.'
      )
    );
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.organization_invitations
    WHERE email = requested_email
      AND status = 'PENDING'
      AND expires_at > now()
  ) THEN
    RETURN '{}'::jsonb;
  END IF;

  RETURN jsonb_build_object(
    'error', jsonb_build_object(
      'http_code', 403,
      'message', 'This email has not been invited to FlowPilot. Ask an organization administrator for access.'
    )
  );
END;
$$;

GRANT USAGE ON SCHEMA public TO supabase_auth_admin;
GRANT EXECUTE ON FUNCTION public.hook_require_invitation(jsonb) TO supabase_auth_admin;
REVOKE EXECUTE ON FUNCTION public.hook_require_invitation(jsonb) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.accept_flowpilot_invitations()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  invitation_record public.organization_invitations%ROWTYPE;
  normalized_email text := lower(btrim(NEW.email));
BEGIN
  IF normalized_email IS NULL OR normalized_email = '' THEN
    RETURN NEW;
  END IF;

  FOR invitation_record IN
    SELECT *
    FROM public.organization_invitations
    WHERE email = normalized_email
      AND status = 'PENDING'
      AND expires_at > now()
    FOR UPDATE
  LOOP
    INSERT INTO public.organization_members (
      organization_id,
      user_id,
      role,
      email,
      display_name
    )
    VALUES (
      invitation_record.organization_id,
      NEW.id,
      invitation_record.role,
      normalized_email,
      COALESCE(NEW.raw_user_meta_data->>'full_name', NEW.raw_user_meta_data->>'name')
    )
    ON CONFLICT (organization_id, user_id) DO UPDATE SET
      role = EXCLUDED.role,
      email = EXCLUDED.email,
      display_name = COALESCE(EXCLUDED.display_name, organization_members.display_name),
      updated_at = now();

    UPDATE public.organization_invitations
    SET status = 'ACCEPTED', accepted_by = NEW.id, last_error = NULL, updated_at = now()
    WHERE id = invitation_record.id;

    INSERT INTO public.access_audit_log (
      organization_id,
      actor_user_id,
      action,
      target_user_id,
      target_email
    )
    VALUES (
      invitation_record.organization_id,
      invitation_record.invited_by,
      'INVITATION_ACCEPTED',
      NEW.id,
      normalized_email
    );
  END LOOP;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS accept_flowpilot_invitations_on_auth_user ON auth.users;
CREATE TRIGGER accept_flowpilot_invitations_on_auth_user
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.accept_flowpilot_invitations();

REVOKE EXECUTE ON FUNCTION public.accept_flowpilot_invitations() FROM PUBLIC, anon, authenticated;

