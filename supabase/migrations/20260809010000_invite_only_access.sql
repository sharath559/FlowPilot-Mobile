CREATE TABLE IF NOT EXISTS public.organization_invitations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  email text NOT NULL CHECK (email = lower(btrim(email)) AND position('@' IN email) > 1),
  role text NOT NULL CHECK (role IN ('ORG_ADMIN', 'SCHOOL_ADMIN', 'STAFF')),
  status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ACCEPTED', 'REVOKED', 'EXPIRED')),
  invited_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  accepted_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  expires_at timestamptz NOT NULL DEFAULT (now() + interval '7 days'),
  last_error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_pending_organization_invitation_email
  ON public.organization_invitations (organization_id, lower(email))
  WHERE status = 'PENDING';

CREATE INDEX IF NOT EXISTS idx_organization_invitations_email
  ON public.organization_invitations (lower(email), status, expires_at);

ALTER TABLE public.organization_members
  ADD COLUMN IF NOT EXISTS email text,
  ADD COLUMN IF NOT EXISTS display_name text,
  ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

UPDATE public.organization_members AS membership
SET email = lower(auth_user.email)
FROM auth.users AS auth_user
WHERE membership.user_id = auth_user.id
  AND membership.email IS NULL;

CREATE TABLE IF NOT EXISTS public.access_audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  actor_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  action text NOT NULL CHECK (action IN ('INVITE_SENT', 'INVITATION_REVOKED', 'INVITATION_ACCEPTED', 'ROLE_CHANGED', 'MEMBER_REMOVED')),
  target_user_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  target_email text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_access_audit_log_organization
  ON public.access_audit_log (organization_id, created_at DESC);

